-- 레거시(빌릴게)에서 이관한 운영진 공용 알림(member_id IS NULL)을 읽음으로 바꾼다.
-- 레거시는 운영진 알림을 읽음 처리한 적이 없어 이관 행이 모두 is_read = 0이다. 운영진 읽음 처리는 한 건씩만 할 수 있어서,
-- 그대로 두면 최근 알림을 다 읽어도 이관 행 때문에 운영진 안 읽은 알림 여부가 계속 true로 남는다.
-- 지금 서버가 만든 운영진 알림과 구분할 값이 없어 안 읽은 운영진 공용 행을 모두 바꾼다. 운영은 아직 배포 전이라 바뀌는 행은 이관 행뿐이다.
UPDATE notifications
SET is_read = 1
WHERE member_id IS NULL
  AND is_read = 0;
