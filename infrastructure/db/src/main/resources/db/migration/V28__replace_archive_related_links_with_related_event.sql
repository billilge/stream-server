-- 아카이빙의 관련 링크를 행사 참조로 바꾼다.
--
-- 관리자 화면이 드롭다운에서 행사를 고르고, 학생 앱은 눌러서 그 행사로 이동한다. 제목+URL로는 식별자를 복원할 수
-- 없어 앱이 어디로 가야 할지 알 수 없고, 저장소에 행사 URL을 만드는 코드도 없다.
-- 제목을 복사해 두면 원본이 수정됐을 때 낡으므로 식별자만 저장하고 제목은 조회 시점에 가져온다.
--
-- 역방향 조회("이 행사를 건 아카이빙 찾기")가 없어 인덱스는 두지 않는다.
ALTER TABLE archives
    ADD COLUMN related_event_id BIGINT NULL;

-- ⚠️ 되돌릴 수 없다. 지운 뒤에는 이전 이미지로 롤백할 수 없다 — ddl-auto: validate가 없는 테이블을 찾아 기동을 막는다.
--    적용 전 SELECT COUNT(*) FROM archive_related_links 로 행 수를 확인한다.
--    연결은 행사 한 건이면 충분하다고 정해서 옮기는 백필을 두지 않았다. 행이 있으면 적용 전에 손으로 옮긴다.
--    그리고 한 파일에 ADD COLUMN과 DROP TABLE이 함께 있는데 MySQL은 DDL을 트랜잭션으로 묶지 않는다.
--    중간에 실패하면 앞 문장이 이미 적용된 채로 남아 손으로 되돌려야 한다 (V21과 같은 상황이다).
DROP TABLE archive_related_links;
