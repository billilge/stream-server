package kr.ac.kookmin.stream.internal.domain.home.domain;

/**
 * 배너 분류. 운영진 목록의 칩과 필터에만 쓰고 학생 앱은 읽지 않는다.
 * <p>
 * 값은 운영진 화면이 정해 보낸다. 분류 칸이 이미지 선택 아래에 있고, 제휴 프리셋을 고르면
 * {@code PARTNERSHIP}이, 그 밖에는 {@code GENERAL}이 자동으로 채워진다. 서버가 {@code imageFileId}로
 * 프리셋을 알아볼 수는 없다 — 프리셋도 {@code files}의 한 행이고 그 식별자는 환경마다 다르다.
 * <p>
 * <b>그래서 분류가 이미지와 맞는지 서버는 검증하지 않는다.</b> 화면이 잘못 보내거나 운영진이 분류만 고쳐도
 * 그대로 저장된다. 이 값에 걸린 서버 불변식이 없고 학생 앱도 읽지 않아, 어긋나면 운영진 목록의 필터에서
 * 한 행이 엉뚱한 칩을 달 뿐이다 — 화면에 그 칩이 보이므로 다시 고칠 수 있다.
 * <p>
 * 랜딩 타입과는 다른 축이다. 제휴 배너가 공지로 갈 수도, 외부 링크로 갈 수도 있다.
 */
public enum HomeBannerType {

    /** 제휴 안내 */
    PARTNERSHIP,
    /** 그 밖의 전부 */
    GENERAL
}
